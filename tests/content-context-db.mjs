// In-memory PostgreSQL only. Install @electric-sql/pglite under an isolated tmp
// prefix, then set PGLITE_MODULE to its ESM entry; no production connection.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
const owner = '11111111-1111-4111-8111-111111111111', other = '22222222-2222-4222-8222-222222222222';
const video = '33333333-3333-4333-8333-333333333333', photo = '44444444-4444-4444-8444-444444444444';
const query = async (sql, values) => (await db.query(sql, values)).rows;
const actor = async id => { await db.exec(`SET ROLE authenticated; SET request.jwt.claim.sub='${id}';`); };
const reset = async () => db.exec('RESET ROLE;');
let checks = 0;
const pass = label => { checks++; console.log('PASS ' + label); };
try {
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
    CREATE SCHEMA auth; CREATE SCHEMA storage;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    GRANT USAGE ON SCHEMA public,auth TO authenticated,anon,service_role;
    CREATE TABLE public.profiles(id uuid PRIMARY KEY);
    CREATE TABLE public.videos(id uuid PRIMARY KEY,owner_id uuid,processing_status text);
    CREATE TABLE public.photos(id uuid PRIMARY KEY,owner_id uuid);
    CREATE TABLE public.user_file_metadata(owner_id uuid,object_path text,is_folder boolean,trashed_at timestamptz,is_favorite boolean DEFAULT false,file_size bigint DEFAULT 7,mime_type text DEFAULT 'text/plain',created_at timestamptz DEFAULT now(),updated_at timestamptz DEFAULT now(),PRIMARY KEY(owner_id,object_path));
    CREATE TABLE storage.objects(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),bucket_id text,name text,metadata jsonb DEFAULT '{"size":7,"mimetype":"text/plain"}');
    INSERT INTO public.profiles VALUES ('${owner}'),('${other}');
    INSERT INTO public.videos VALUES ('${video}','${owner}','ready'); INSERT INTO public.photos VALUES ('${photo}','${owner}');
    INSERT INTO public.user_file_metadata(owner_id,object_path,is_folder) VALUES
      ('${owner}','${owner}/Src',true),('${owner}','${owner}/Src/Sub',true),('${owner}','${owner}/Src/Sub/file.txt',false),('${owner}','${owner}/Dest',true),('${other}','${other}/Other',true);
    INSERT INTO storage.objects(bucket_id,name) VALUES ('user-files','${owner}/Src/.folder'),('user-files','${owner}/Src/Sub/.folder'),('user-files','${owner}/Src/Sub/file.txt'),('user-files','${owner}/Dest/.folder');`);
  await db.exec(await fs.readFile(new URL('../supabase/migrations/20261003130000_file_catalog_integrity.sql', import.meta.url), 'utf8'));
  await db.exec(await fs.readFile(new URL('../supabase/migrations/20261007010000_content_context_actions.sql', import.meta.url), 'utf8'));
  await db.exec(await fs.readFile(new URL('../supabase/migrations/20261007020000_reuse_trashed_file_names.sql', import.meta.url), 'utf8'));
  pass('migration applies to PostgreSQL with required existing tables');
  await actor(owner);
  const params = ['video', video, 'a'.repeat(64), null];
  const first = (await query('SELECT public.create_temporary_share($1,$2,$3,$4) AS result', params))[0].result;
  assert.ok(first.id); assert.ok(first.expires_at);
  await assert.rejects(query("SELECT * FROM public.temporary_content_shares"), /permission denied/);
  await assert.rejects(query('SELECT public.create_temporary_share($1,$2,$3,$4)', ['video', video, 'b'.repeat(64), null]), /active link already exists/);
  const second = (await query('SELECT public.create_temporary_share($1,$2,$3,$4) AS result', ['video', video, 'b'.repeat(64), first.id]))[0].result;
  await reset();
  const links = await query('SELECT id,token_hash,revoked_at,expires_at-created_at AS lifespan FROM public.temporary_content_shares ORDER BY created_at');
  assert.equal(links.length, 2); assert.ok(links[0].revoked_at); assert.equal(links[1].revoked_at, null);
  assert.equal((await query("SELECT bool_and(extract(epoch FROM expires_at-created_at)=86400) AS okay FROM public.temporary_content_shares"))[0].okay, true);
  assert.equal((await query("SELECT count(*)::int AS n FROM public.temporary_content_shares WHERE revoked_at IS NULL"))[0].n, 1);
  pass('hash-only storage, exact 24 hours, one active link, confirmed replacement race check');
  await actor(other);
  await assert.rejects(query('SELECT public.create_temporary_share($1,$2,$3,$4)', ['photo', photo, 'c'.repeat(64), null]), /Only the owner/);
  await assert.rejects(query('SELECT public.revoke_temporary_share($1)', [second.id]), /Only the owner/);
  await assert.rejects(query('SELECT public.plan_file_operation($1,$2,false)', [owner + '/Src', other + '/Other/Src']), /permission/);
  await db.exec('SET ROLE anon;');
  await assert.rejects(query('SELECT public.get_temporary_share($1,$2)', ['video', video]), /permission denied/);
  await assert.rejects(query('SELECT public.temporary_share_children($1)', ['b'.repeat(64)]), /permission denied/);
  pass('non-owner creation, revocation and operations denied; anonymous RPC access denied');
  await actor(owner);
  await query('SELECT public.revoke_temporary_share($1)', [second.id]);
  assert.equal((await query('SELECT public.get_temporary_share($1,$2) AS link', ['video', video]))[0].link, null);
  const folderLink = (await query('SELECT public.create_temporary_share($1,$2,$3,NULL) AS result', ['folder', owner + '/Src', 'd'.repeat(64)]))[0].result;
  await reset(); await db.exec('SET ROLE service_role;');
  const root = (await query('SELECT public.temporary_share_children($1) AS children', ['d'.repeat(64)]))[0].children;
  assert.deepEqual(root.map(row => row.relative), ['Sub']);
  const children = (await query('SELECT public.temporary_share_children($1,$2) AS children', ['d'.repeat(64), 'Sub']))[0].children;
  assert.deepEqual(children.map(row => row.relative), ['Sub/file.txt']);
  assert.equal((await query('SELECT public.temporary_share_children($1,$2) AS children', ['d'.repeat(64), '../Dest']))[0].children, null);
  await reset();
  await db.exec(`UPDATE public.temporary_content_shares SET created_at=clock_timestamp()-interval '25 hours',expires_at=clock_timestamp()-interval '1 hour' WHERE id='${folderLink.id}';`);
  assert.equal((await query('SELECT public.temporary_share_children($1) AS children', ['d'.repeat(64)]))[0].children, null);
  pass('folder capability lists only its subtree; rejects traversal and expired links');
  await actor(owner);
  await assert.rejects(query('SELECT public.plan_file_operation($1,$2,false)', [owner + '/Src', owner + '/Src']), /inside itself/);
  await assert.rejects(query('SELECT public.plan_file_operation($1,$2,false)', [owner + '/Src', owner + '/Src/Sub/Src']), /inside itself/);
  await assert.rejects(query('SELECT public.plan_file_operation($1,$2,true)', [owner + '/Src', other + '/Other/Src']), /permission/);
  await assert.rejects(query('SELECT public.plan_file_operation($1,$2,true)', [owner + '/Src', owner + '/Missing/Src']), /existing destination/);
  const plan = (await query('SELECT public.plan_file_operation($1,$2,true) AS plan', [owner + '/Src', owner + '/Dest/Src']))[0].plan;
  assert.equal(plan.objects.length, 3); assert.equal(plan.metadata.length, 3);
  const conflict = (await query('SELECT public.plan_file_operation($1,$2,true) AS plan', [owner + '/Src', owner + '/Src']))[0].plan;
  assert.equal(conflict.conflict, true);
  pass('server checks destination ownership/existence, cycles, conflicts and full recursive plans');
  await reset();
  await db.exec(`UPDATE storage.objects SET name=replace(name,'${owner}/Src/','${owner}/Moved/') WHERE bucket_id='user-files' AND starts_with(name,'${owner}/Src/');`);
  await db.exec(`UPDATE public.user_file_metadata SET object_path='${owner}/Moved' WHERE owner_id='${owner}' AND object_path='${owner}/Src';`);
  assert.equal((await query('SELECT content_id FROM public.temporary_content_shares WHERE id=$1', [folderLink.id]))[0].content_id, owner + '/Moved');
  await db.exec(`DELETE FROM public.videos WHERE id='${video}';`);
  assert.equal((await query("SELECT count(*)::int AS n FROM public.temporary_content_shares WHERE content_type='video'"))[0].n, 0);
  await db.exec(`DELETE FROM public.user_file_metadata WHERE owner_id='${owner}' AND object_path='${owner}/Moved';`);
  assert.equal((await query('SELECT count(*)::int AS n FROM public.temporary_content_shares WHERE id=$1', [folderLink.id]))[0].n, 0);
  pass('moved identity follows metadata; deleted videos/files cascade to capability deletion');
} finally { await db.close(); }
console.log(`${checks} PostgreSQL checks passed`);
